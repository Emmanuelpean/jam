CREATE TABLE job (
	title VARCHAR NOT NULL, 
	description VARCHAR, 
	salary_min FLOAT, 
	salary_max FLOAT, 
	salary_currency VARCHAR, 
	url VARCHAR, 
	personal_rating INTEGER, 
	note VARCHAR, 
	deadline TIMESTAMP WITH TIME ZONE, 
	followup_snooze_datetime TIMESTAMP WITH TIME ZONE, 
	attendance_type VARCHAR, 
	application_date TIMESTAMP WITH TIME ZONE, 
	application_url VARCHAR, 
	application_status VARCHAR, 
	applied_via VARCHAR, 
	application_note VARCHAR, 
	company_id INTEGER, 
	location_id INTEGER, 
	duplicate_id INTEGER, 
	source_id INTEGER, 
	application_aggregator_id INTEGER, 
	cv_id INTEGER, 
	cover_letter_id INTEGER, 
	owner_id INTEGER NOT NULL, 
	id SERIAL NOT NULL, 
	created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
	modified_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
	PRIMARY KEY (id), 
	CONSTRAINT valid_rating_range CHECK (personal_rating >= 1 AND personal_rating <= 5), 
	CONSTRAINT valid_salary_range CHECK (salary_min <= salary_max), 
	CONSTRAINT valid_attendance_type_values CHECK (attendance_type IN ('on-site', 'remote', 'hybrid')), 
	CONSTRAINT valid_application_status_values CHECK (application_status IN ('applied', 'interview', 'offer', 'rejected', 'withdrawn')), 
	CONSTRAINT valid_applied_via_values CHECK (applied_via IN ('aggregator', 'email', 'phone', 'other')), 
	FOREIGN KEY(company_id) REFERENCES company (id) ON DELETE SET NULL, 
	FOREIGN KEY(location_id) REFERENCES location (id) ON DELETE SET NULL, 
	FOREIGN KEY(duplicate_id) REFERENCES job (id) ON DELETE SET NULL, 
	FOREIGN KEY(source_id) REFERENCES aggregator (id) ON DELETE SET NULL, 
	FOREIGN KEY(application_aggregator_id) REFERENCES aggregator (id) ON DELETE SET NULL, 
	FOREIGN KEY(cv_id) REFERENCES file (id) ON DELETE SET NULL, 
	FOREIGN KEY(cover_letter_id) REFERENCES file (id) ON DELETE SET NULL, 
	FOREIGN KEY(owner_id) REFERENCES "user" (id) ON DELETE CASCADE
);

