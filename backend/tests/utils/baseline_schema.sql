-- Schema of the public database immediately before the Alembic chain begins.
--
-- Generated from the SQLAlchemy models at commit 86ea019d~1 (2025-10-12), the parent of
-- "Implement email verification feature", which introduced the columns the root revision
-- 8a882611d98c adds. Sources at that commit were backend/app/models.py and
-- backend/app/eis/models.py; Base lived in app/database.py and the only settings value the
-- models read was min_password_length (8), inlined below in the user check constraint.
--
-- The migration chain cannot build a database from scratch: 8a882611d98c starts with
-- op.add_column("user", ...) because it was autogenerated against a schema create_all had
-- already produced. This file is that schema, so the chain can be replayed from it in
-- tests/test_migrations.py.
--
-- This is a record of history: do not regenerate or edit it to match the current models.
-- alembic_version is deliberately absent, alembic creates it on the first upgrade.

